"""Certificate data for the coverage facts C1(5), C2(5) of audit/PROOF.md (mu_4(5); mu4-proof/lean, 2026-11-05, second agent).

Every 2-dim subspace of A5 = GF(4^5) is x * span(1, z) with z not in GF(4).  For each code z in 4..1023:
  C1: (k, s, ab, cd) with (a + b z) * sigma^s(p1_k) = c + d z, (a, b) != 0, P_k = span(1, p1_k) of pList;
  C2: (j, ab, cd)    with (a + b z) * s1_j          = c + d z, (a, b) != 0, S_j = span(1, s1_j) of sList;
where a = ab & 3, b = ab >> 2, c = cd & 3, d = cd >> 2 are GF(4) codes and sigma(x) = x^2.
Packed into natural numbers: C1 entry z = (k << 12) | (s << 8) | (ab << 4) | cd in bits 16z..16z+15 (k < 3, s < 10),
C2 entry z = (j << 8) | (ab << 4) | cd in bits 16z..16z+15 (j < 17), frobTab5 entry 10k + s = sigma^s(p1_k) in 10 bits.
The Lean kernel re-checks every entry (Mu4/N5/Cover5.lean); this script only finds the witnesses.
Usage: python3 gen_cover5.py > ../Mu4/N5/CoverData5.lean"""
import sys
sys.set_int_max_str_digits(100000)
sys.path.insert(0, '.')
from gen_tables5 import polymul
def dec(x): return [(x >> (2*l)) & 3 for l in range(5)]
def code(v): return sum(c << (2*l) for l, c in enumerate(v))
MUL = {}
def mul(a, b):
    key = (a, b) if a <= b else (b, a)
    r = MUL.get(key)
    if r is None:
        r = code(polymul(dec(a), dec(b))); MUL[key] = r
    return r
# exp/log tables for speed (a primitive element is found by search; checked against polymul)
def order(g):
    x, n = g, 1
    while x != 1:
        x = mul(x, g); n += 1
    return n
g = next(c for c in range(2, 1024) if order(c) == 1023)
EXP = [1]*1023
for i in range(1, 1023): EXP[i] = mul(EXP[i-1], g)
LOG = {EXP[i]: i for i in range(1023)}
assert len(LOG) == 1023
def fmul(a, b):
    if a == 0 or b == 0: return 0
    return EXP[(LOG[a] + LOG[b]) % 1023]
for a, b in [(5, 77), (1023, 1000), (234, 345), (2, 3)]:
    assert fmul(a, b) == mul(a, b)
def lin(ab, z): return fmul(ab & 3, 1) ^ fmul(ab >> 2, z)
pList = [(1, 4), (1, 20), (1, 28)]
sList = [(1, 4), (1, 16), (1, 20), (1, 52), (1, 36), (1, 64), (1, 196), (1, 132), (1, 164), (1, 212), (1, 180),
   (1, 116), (1, 228), (1, 772), (1, 516), (1, 784), (1, 532)]
assert len(pList) == 3 and len(sList) == 17 and all(p0 == 1 for p0, _ in pList + sList)
def frob(x): return fmul(x, x)
FT = []
for k in range(3):
    x = pList[k][1]
    for s in range(10):
        FT.append(x); x = frob(x)
    assert x == pList[k][1]
def find(z, ts):
    span = {lin(cd, z): cd for cd in range(16)}
    for idx, t in ts:
        for ab in range(1, 16):
            cd = span.get(fmul(lin(ab, z), t))
            if cd is not None: return idx, ab, cd
    return None
c1 = [0]*1024; c2 = [0]*1024
for z in range(4, 1024):
    k_s, ab, cd = find(z, [((k, s), FT[10*k + s]) for k in range(3) for s in range(10)])
    c1[z] = (k_s[0] << 12) | (k_s[1] << 8) | (ab << 4) | cd
    j, ab, cd = find(z, [(j, sList[j][1]) for j in range(17)])
    c2[z] = (j << 8) | (ab << 4) | cd
# self-check of every entry with the slow multiplication
for z in range(4, 1024):
    e = c1[z]; k, s, ab, cd = e >> 12, (e >> 8) & 15, (e >> 4) & 15, e & 15
    assert k < 3 and s < 10 and ab != 0 and mul(lin(ab, z), FT[10*k + s]) == lin(cd, z)
    e = c2[z]; j, ab, cd = e >> 8, (e >> 4) & 15, e & 15
    assert j < 17 and ab != 0 and mul(lin(ab, z), sList[j][1]) == lin(cd, z)
C1 = sum(c1[z] << (16*z) for z in range(1024))
C2 = sum(c2[z] << (16*z) for z in range(1024))
FTN = sum(FT[i] << (10*i) for i in range(30))
print("""/-!
# Certificate data for the coverage facts C1(5), C2(5) (generated by `lean/tools/gen_cover5.py`)

Entry `z` of `c1Tab5`, `c2Tab5` (16 bits each) is a witness for the code `z` (`4 ≤ z < 1024`), and entry `10 k + s`
of `frobTab5` (10 bits) is `σ^s(p1_k)`; see `Mu4/N5/Cover5.lean`, where the kernel checks every entry. No Mathlib
import. SECRET until 2027-01-20.
-/

namespace Mu4.N5
""")
print("/-- C1(5) witnesses: entry `z` is `(k << 12) | (s << 8) | (ab << 4) | cd`. -/")
print("def c1Tab5 : Nat := " + str(C1) + "\n")
print("/-- C2(5) witnesses: entry `z` is `(j << 8) | (ab << 4) | cd`. -/")
print("def c2Tab5 : Nat := " + str(C2) + "\n")
print("/-- `σ^s(p1_k)` at entry `10 k + s`, for the three pencil representatives `span(1, p1_k)`. -/")
print("def frobTab5 : Nat := " + str(FTN) + "\n")
print("end Mu4.N5")
import collections
print("-- stats: C1 k histogram", sorted(collections.Counter(c1[z] >> 12 for z in range(4, 1024)).items()), file=sys.stderr)
print("-- stats: C2 j used", len(set(c2[z] >> 8 for z in range(4, 1024))), file=sys.stderr)
