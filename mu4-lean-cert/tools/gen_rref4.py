"""Witness tables for the kernel proof of rref_cover (mu_4(6) certificate, second agent, 11-06).

For every pair (u, u') of 8-bit codes (vectors of GF(4)^4), one 24-bit entry:
- if u, u' are dependent: e = ab with ab != 0 and a u + b u' = 0 (a = coordinate 0 of ab, b = coordinate 1),
  so e < 16 and e / 65536 = 0;
- if they are independent: e = (r0 << 16) | (r1 << 8) | (ab << 4) | cd, where (r0, r1) is a reduced echelon pair
  of rrefPairs (r0 != 0) with r0 = a u + b u' (ab) and r1 = c u + d u' (cd).
The table is cut into 16 chunks: chunk k holds u = 16 k .. 16 k + 15, entry 256 (u - 16 k) + u' at bit 24 times
that index. The Lean kernel re-checks every entry (Mu4/Bridge/RrefCheck*.lean); this script checks them too.
usage: python3 -I gen_rref4.py [first_chunk last_chunk]  (prints Lean definitions rrefTab<k>)"""
import sys
sys.set_int_max_str_digits(0)
M4 = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
def coord(x, l): return (x >> (2 * l)) & 3
def smul(c, x): return sum(M4[c][coord(x, l)] << (2 * l) for l in range(4))
def first_nz(x):
    for l in range(4):
        if coord(x, l): return l
    return None
def cond(r0, r1):
    p, q = first_nz(r0), first_nz(r1)
    return p is not None and q is not None and p < q and coord(r0, p) == 1 and coord(r1, q) == 1 and coord(r0, q) == 0
rref = [(r0, r1) for r0 in range(256) for r1 in range(256) if cond(r0, r1)]
assert len(rref) == 357, len(rref)
def lin(ab, u, v): return smul(ab & 3, u) ^ smul(ab >> 2, v)
def indep(u, v): return all(ab == 0 or lin(ab, u, v) % 256 != 0 for ab in range(16))
def entry(u, v):
    span = {}
    for ab in range(16):
        span.setdefault(lin(ab, u, v), ab)
    if not indep(u, v):
        ab = next(ab for ab in range(1, 16) if lin(ab, u, v) % 256 == 0)
        return ab
    r0, r1 = next(K for K in rref if K[0] in span and K[1] in span)
    return (r0 << 16) | (r1 << 8) | (span[r0] << 4) | span[r1]
def check(e, u, v):
    """The Lean check rrefEntryOK, in Python."""
    if e // 65536 == 0:
        return e % 16 != 0 and lin(e % 16, u, v) % 256 == 0
    r0, r1 = e // 65536, e // 256 % 256
    return cond(r0, r1) and lin(e // 16 % 16, u, v) == r0 and lin(e % 16, u, v) == r1
ndep = 0
lits = []
for k in range(16):
    t = 0
    for i in range(16):
        u = 16 * k + i
        for v in range(256):
            e = entry(u, v)
            assert e < 1 << 24 and check(e, u, v)
            ndep += e // 65536 == 0
            assert (e // 65536 == 0) == (not indep(u, v))
            t |= e << (24 * (256 * i + v))
    lits.append(t)
assert ndep == 1276, ndep
def emit(k):
    print(f'/-- Witnesses for u = {16 * k} .. {16 * k + 15} (lean/tools/gen_rref4.py). -/')
    print(f'def rrefTab{k} : Nat := {lits[k]}')
    print()
if len(sys.argv) > 2 and sys.argv[1] == 'module':
    # the whole module Mu4/Bridge/RrefCheck<N>.lean, N = 1..4, with chunks 4 (N - 1) .. 4 N - 1
    n = int(sys.argv[2])
    ks = range(4 * (n - 1), 4 * n)
    print('import Mu4.Bridge.RrefDefs')
    print()
    print('/-!')
    print(f'# The reduced echelon pairs of GF(4)^4 cover every plane: kernel check, part {n} of 4')
    print()
    print(f'Generated by `python3 -I lean/tools/gen_rref4.py module {n}` (second agent, 11-06). Chunks {ks[0]}-{ks[-1]}: the')
    print(f'witness entries of u = {16 * ks[0]} .. {16 * ks[-1] + 15} and all u\' < 256, each checked by the kernel')
    print('(`decide +kernel`, about 31 s and 2.4 GB per chunk, measured 11-06). The meaning is in Mu4/Bridge/Rref.lean.')
    print('Core Lean only. No `native_decide`.')
    print('-/')
    print()
    print('set_option autoImplicit false')
    print()
    print('namespace Mu4.Bridge')
    print()
    for k in ks:
        emit(k)
    for k in ks:
        print(f'theorem rref_chunk_{k} : rrefChunkOK rrefTab{k} {16 * k} = true := by decide +kernel')
        print()
    print('end Mu4.Bridge')
else:
    lo, hi = (int(sys.argv[1]), int(sys.argv[2])) if len(sys.argv) > 2 else (0, 15)
    for k in range(lo, hi + 1):
        emit(k)
print(f'-- stats: {len(rref)} echelon pairs, {ndep} dependent pairs, {65536 - ndep} independent', file=sys.stderr)
